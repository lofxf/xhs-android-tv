#!/usr/bin/env python3
"""Patches a FongMi/TV checkout into a separately installable "小红书TV" build.

- applicationId com.fongmi.android.tv -> com.fongmi.android.tv.xhs (installs next to the original)
- app name -> 小红书TV
- first-run default VOD config -> this repo's 小红书/B站 config
Usage: patch.py <fongmi_dir> <config_url>
"""
import pathlib
import re
import sys

root = pathlib.Path(sys.argv[1])
config_url = sys.argv[2]
APP_ID = "com.fongmi.android.tv.xhs"
APP_NAME = "小红书TV"


def edit(path, old, new, count=1):
    p = root / path
    s = p.read_text(encoding="utf-8")
    if old not in s:
        raise SystemExit(f"patch target not found in {path}: {old!r}")
    p.write_text(s.replace(old, new, count), encoding="utf-8")
    print(f"patched {path}")


# 1. Separate package so it can be installed alongside the original FongMi.
edit("app/build.gradle", 'applicationId "com.fongmi.android.tv"', f'applicationId "{APP_ID}"')

# 2. App name (all locales).
for strings in root.glob("app/src/*/res/values*/strings.xml"):
    s = strings.read_text(encoding="utf-8")
    n = re.sub(r'<string name="app_name">[^<]*</string>', f'<string name="app_name">{APP_NAME}</string>', s)
    if n != s:
        strings.write_text(n, encoding="utf-8")
        print(f"patched {strings.relative_to(root)}")

# 3. Default VOD config on first launch (users can still change it in settings).
edit("app/src/main/java/com/fongmi/android/tv/bean/Config.java",
     "return item == null ? create(0) : item;",
     f'return item == null ? create(0, "{config_url}", "{APP_NAME}") : item;')

# 4. Own launcher icon + Android TV / Fire TV banner (generated by make_icons.py).
import shutil

res = pathlib.Path(__file__).resolve().parent / "res"
for src, dst in [("xhs_icon.png", "app/src/main/res/drawable-nodpi/xhs_icon.png"),
                 ("xhs_banner.png", "app/src/leanback/res/drawable-nodpi/xhs_banner.png")]:
    target = root / dst
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(res / src, target)
    print(f"added {dst}")
edit("app/src/main/AndroidManifest.xml", 'android:icon="@mipmap/ic_launcher"', 'android:icon="@drawable/xhs_icon"')
edit("app/src/main/AndroidManifest.xml", 'android:roundIcon="@mipmap/ic_launcher_round"', 'android:roundIcon="@drawable/xhs_icon"')
edit("app/src/leanback/AndroidManifest.xml", 'android:banner="@mipmap/ic_banner"', 'android:banner="@drawable/xhs_banner"')
